import { Router } from 'express';
import * as c from '../controllers/news.controller.js';
import { requireAuth } from '../middleware/auth.middleware.js';
import { requireRole } from '../middleware/role.middleware.js';
import { validate } from '../middleware/validation.middleware.js';
import { createNewsSchema, updateNewsSchema } from '../validators/news.validator.js';
const router = Router();
router.get('/', c.list);
router.get('/saved', requireAuth, c.saved);
router.get('/my', requireAuth, requireRole('editor'), c.myList);
router.get('/my/:id', requireAuth, requireRole('editor'), c.myGet);
router.get('/:slug', c.getBySlug);
router.post('/', requireAuth, requireRole('editor'), validate(createNewsSchema), c.create);
router.patch('/:id', requireAuth, requireRole('editor'), validate(updateNewsSchema), c.update);
router.delete('/:id', requireAuth, requireRole('editor'), c.remove);
router.patch('/:id/publish', requireAuth, requireRole('editor'), c.publish);
router.patch('/:id/unpublish', requireAuth, requireRole('editor'), c.unpublish);
router.post('/:id/save', requireAuth, c.save);
router.delete('/:id/save', requireAuth, c.unsave);
export default router;
